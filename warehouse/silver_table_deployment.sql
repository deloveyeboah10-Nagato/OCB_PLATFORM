/*========================================================================================================================*

    OCB PLATFORM v1.0.0

    SILVER SOURCE-LAYER TABLE DEPLOYMENT

    Purpose:
        Establish the Silver layer for the frozen synthetic source dataset,
        controlled reference data, provenance, and OCB-wide customer identity
        resolution.

    Architecture:

        FROZEN GENERATOR OUTPUT
                    ↓
                 BRONZE
                    ↓
                 SILVER
                    ↓
                  GOLD
                    ↓
              INTELLIGENCE


    SILVER PRINCIPLE:

        Silver preserves source-world evidence while applying controlled
        standardisation, identity resolution, and analytical conformance.


    SILVER CONFORMANCE:

        Native source identifiers are preserved.

        ocb_customer_id is the canonical OCB-wide surrogate customer identity.

        ocb_customer_id is generated by the approved Silver identity-resolution
        process from the Bronze source customer records.

        ocb_customer_identity maps each source-system customer identity to its
        resolved OCB customer identity.

        ocb_customer_id replaces the previously proposed ocb_customer_key.

        ocb_customer_key does not exist in the redesigned Silver layer.


    SILVER CONTAINS:

        PROVENANCE
            load_batch

        REFERENCE DATA
            ref_transaction_type
            ref_transaction_status
            ref_transaction_channel
            ref_currency
            ref_country

        OCB CUSTOMER RESOLUTION
            ocb_customer
            ocb_customer_identity

        ANANSE
            ananse_customer
            ananse_wallet
            ananse_transaction

        SIKACREDIT
            sikacredit_customer
            sikacredit_loan
            sikacredit_repayment

        OMAN REMIT
            oman_remit_customer
            oman_remit_remittance


    OCB CUSTOMER IDENTITY MODEL:

        source_entity
        source_customer_id
                ↓
        ocb_customer_id


    IMPORTANT:

        - Native source identifiers are retained.
        - ocb_customer_id is the canonical OCB surrogate customer identity.
        - ocb_customer_key is not created.
        - Source customer records are not deleted after identity resolution.
        - flag = 1 identifies the canonical source record used to populate
          ocb_customer attributes.
        - flag > 1 remains valid source identity evidence and is retained in
          ocb_customer_identity.
        - Source-specific attributes remain unchanged.
        - No Gold tables are created here.
        - No analytical/business rules are applied here.
        - Reference tables retain their Silver ref_* naming.


    EXPECTED SILVER TABLES:

        16 total

        1   load_batch
        5   reference
        2   OCB customer resolution
        3   Ananse
        3   SikaCredit
        2   Oman Remit


*========================================================================================================================*/
