/*========================================================================================================================*

    10. OCB CUSTOMER IDENTITY

    Maps source-system customer identities to the canonical OCB customer.

    One OCB customer may have multiple source-system identities.

    Example:

        OCB_CUSTOMER_ID = 4

            OMAN_REMIT  OR-C000002
            SIKACREDIT  SC-C000002

*========================================================================================================================*/
CREATE TABLE silver.[ocb_customer_identity] (
    source_entity      NVARCHAR(150) NOT NULL,
    source_customer_id VARCHAR(100) NOT NULL,
    cross_domain_id    VARCHAR(100) NOT NULL,
    ocb_customer_id    BIGINT NOT NULL,
    CONSTRAINT PK_silver_ocb_customer_identity PRIMARY KEY (
        source_entity,     
        source_customer_id 
        ),                 
    CONSTRAINT FK_silver_ocb_customer_identity_customer FOREIGN KEY (ocb_customer_id)
    REFERENCES         silver.[ocb_customer](ocb_customer_id)
    );
GO

CREATE INDEX idx_silver_ocb_customer_identity_cross_domain_id ON silver.[ocb_customer_identity] (cross_domain_id);

CREATE INDEX idx_silver_ocb_customer_identity_ocb_customer_id ON silver.[ocb_customer_identity] (ocb_customer_id);
GO

